import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import * as THREE from '../dist/assets/three.module.js';
const root=new URL('../',import.meta.url);
const path=new URL('dist/building-structures.js',root);
const src=await readFile(path,'utf8');
const baseline=(await readFile(new URL('research/buildings/008/other-buildings.sha256',root),'utf8')).trim();
const without8=s=>s.slice(0,s.indexOf('function doosan8(b){')).replace(/\/\/ 8동:[\s\S]*$/,'')+s.slice(s.indexOf('// --- 12동'));
assert.equal(createHash('sha256').update(without8(src)).digest('hex'),baseline,'Other building geometry changed');
const {createBuildingStructure}=await import('data:text/javascript;base64,'+Buffer.from(src.replace("from 'three'",`from '${new URL('dist/assets/three.module.js',root).href}'`)).toString('base64'));
const b=JSON.parse(await readFile(new URL('dist/data/campus.json',root),'utf8')).buildings.find(b=>b.number==='8');
const {group}=createBuildingStructure(b); group.position.set(0,0,0);group.rotation.set(0,0,0);group.updateMatrixWorld(true);
const distance=(p,d)=>new THREE.Raycaster(new THREE.Vector3(...p),new THREE.Vector3(...d)).intersectObject(group,true)[0]?.distance ?? Infinity;
assert.ok(distance([b.box.width*.3,3,-b.box.depth/2-10],[0,0,1])>15,'Front entry is blocked');
assert.ok(distance([b.box.width/2+10,3,0],[-1,0,0])>15,'Side entry is blocked');
assert.ok(distance([b.box.width*.38,20,-b.box.depth/2-10],[0,0,1])>10.5,'Terrace screen hole is blocked');
assert.ok(group.getObjectByName('two-level-projecting-bay'));
assert.ok(!group.getObjectByName('cantilevered-metal-bay'));
console.log('PASS: 8동 front / side entry voids, open terrace screen; all other building source unchanged.');
